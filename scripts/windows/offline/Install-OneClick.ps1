#Requires -RunAsAdministrator
<#
  نصب یک‌کلیک آمادبان برای Windows Server 2019 — بدون اینترنت روی سرور.
  همهٔ فایل‌ها از BundleRoot (پوشه Amadban-Offline روی USB/دیسک) خوانده می‌شود.
#>
param(
    [string]$BundleRoot = '',
    [string]$InstallRoot = 'C:\Amadban',
    [int]$LanPort = 8088,
    [string]$PostgresServiceName = 'postgresql-amadban'
)

$ErrorActionPreference = 'Stop'

function Write-Step($msg) { Write-Host "`n==> $msg" -ForegroundColor Cyan }

function New-AmadbanPassword([int]$Length = 16) {
    $chars = 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789'
    $bytes = [byte[]]::new($Length)
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

function Read-ServiceEnv($path) {
    $h = @{}
    if (-not (Test-Path $path)) { return $h }
    Get-Content $path -Encoding UTF8 | ForEach-Object {
        $line = $_.Trim()
        if ($line -eq '' -or $line.StartsWith('#')) { return }
        if ($line -match '^([^=]+)=(.*)$') { $h[$Matches[1].Trim()] = $Matches[2].Trim() }
    }
    $h
}

function Write-ServiceEnv($path, $hash) {
    $lines = @(
        '# Auto-generated by Install-OneClick.ps1 - server admins only',
        'ASPNETCORE_ENVIRONMENT=Production',
        "ASPNETCORE_URLS=http://0.0.0.0:$LanPort",
        'AMADBAN_DB_HOST=127.0.0.1',
        "AMADBAN_DB_PASSWORD=$($hash['AMADBAN_DB_PASSWORD'])",
        "AMADBAN_ADMIN_PASSWORD=$($hash['AMADBAN_ADMIN_PASSWORD'])",
        "AMADBAN_KEYS=$($hash['AMADBAN_KEYS'])"
    )
    $dir = Split-Path $path -Parent
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    Set-Content -Path $path -Value $lines -Encoding UTF8
}

function Find-PostgresInstaller($dir) {
    if (-not (Test-Path $dir)) { return $null }
    Get-ChildItem -Path $dir -File -Filter 'postgresql-*-windows-x64.exe' -ErrorAction SilentlyContinue | Select-Object -First 1
}

function Get-PsqlPath {
    $candidates = @(
        'C:\Program Files\PostgreSQL\17\bin\psql.exe',
        'C:\Program Files\PostgreSQL\16\bin\psql.exe',
        'C:\Program Files\PostgreSQL\15\bin\psql.exe'
    )
    foreach ($p in $candidates) { if (Test-Path $p) { return $p } }
    Get-ChildItem 'C:\Program Files\PostgreSQL\*\bin\psql.exe' -ErrorAction SilentlyContinue | Select-Object -First 1 -ExpandProperty FullName
}

function Test-PostgresReady([string]$superPassword) {
    $psql = Get-PsqlPath
    if (-not $psql) { return $false }
    $env:PGPASSWORD = $superPassword
    $out = & $psql -h 127.0.0.1 -U postgres -d postgres -tAc 'SELECT 1' 2>$null
    Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue
    return ($out -eq '1')
}

function Install-PostgresFromBundle($installer, $superPassword, $dataRoot, $serviceName) {
    if (-not (Test-Path $installer)) { throw "PostgreSQL installer missing: $installer" }
    $vc = Join-Path (Split-Path $installer -Parent) 'vcredist\VC_redist.x64.exe'
    if (Test-Path $vc) {
        Write-Step 'Installing bundled VC++ runtime (offline)'
        Start-Process -FilePath $vc -ArgumentList '/install', '/quiet', '/norestart' -Wait -PassThru | Out-Null
    }
    $args = @(
        '--mode', 'unattended',
        '--unattendedmodeui', 'none',
        '--superpassword', $superPassword,
        '--serverport', '5432',
        '--servicename', $serviceName,
        "--datadir", (Join-Path $dataRoot 'pgsql-data'),
        '--install_runtimes', '0',
        '--enable_acledit', '0'
    )
    Write-Step "Installing PostgreSQL from $(Split-Path $installer -Leaf)"
    $p = Start-Process -FilePath $installer.FullName -ArgumentList $args -Wait -PassThru
    if ($p.ExitCode -ne 0) { throw "PostgreSQL installer exit code $($p.ExitCode)" }
    Start-Sleep -Seconds 5
    $svc = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
    if ($svc -and $svc.Status -ne 'Running') { Start-Service $serviceName }
}

function Ensure-AmadbanDatabase($dbPassword, $superPassword) {
    $psql = Get-PsqlPath
    if (-not $psql) { throw 'psql.exe not found after PostgreSQL install' }
    $pwdSql = $dbPassword -replace "'", "''"
    $env:PGPASSWORD = $superPassword
    $exists = & $psql -h 127.0.0.1 -U postgres -d postgres -tAc "SELECT 1 FROM pg_roles WHERE rolname='amadban'" 2>$null
    if ($exists -ne '1') {
        & $psql -h 127.0.0.1 -U postgres -d postgres -v ON_ERROR_STOP=1 -c "CREATE USER amadban WITH PASSWORD '$pwdSql';" | Out-Null
    }
    else {
        & $psql -h 127.0.0.1 -U postgres -d postgres -v ON_ERROR_STOP=1 -c "ALTER USER amadban WITH PASSWORD '$pwdSql';" | Out-Null
    }
    $dbExists = & $psql -h 127.0.0.1 -U postgres -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname='amadban'" 2>$null
    if ($dbExists -ne '1') {
        & $psql -h 127.0.0.1 -U postgres -d postgres -v ON_ERROR_STOP=1 -c "CREATE DATABASE amadban OWNER amadban;" | Out-Null
    }
    Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue
}

if ([string]::IsNullOrWhiteSpace($BundleRoot)) {
    $BundleRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
}
$BundleRoot = (Resolve-Path $BundleRoot).Path
$appSrc = Join-Path $BundleRoot 'app'
$publish = Join-Path $InstallRoot 'publish'
$keys = Join-Path $InstallRoot 'keys'
$config = Join-Path $InstallRoot 'config'
$envFile = Join-Path $config 'service.env'
$pgMeta = Join-Path $config 'postgres.env'
$dataRoot = Join-Path $InstallRoot 'data'
$postgresBundle = Join-Path $BundleRoot 'postgres'

Write-Step "Bundle: $BundleRoot"
if (-not (Test-Path (Join-Path $appSrc 'Amadban.exe')) -and -not (Test-Path (Join-Path $appSrc 'Amadban.dll'))) {
    throw "app folder incomplete. Run Build-OfflineBundle first. Expected: $appSrc"
}

New-Item -ItemType Directory -Force -Path $publish, $keys, $config, $dataRoot | Out-Null

$envVars = Read-ServiceEnv $envFile
$pgVars = Read-ServiceEnv $pgMeta
$isNew = -not $envVars['AMADBAN_DB_PASSWORD']

if ($isNew) {
    $envVars['AMADBAN_DB_PASSWORD'] = New-AmadbanPassword 20
    $envVars['AMADBAN_ADMIN_PASSWORD'] = New-AmadbanPassword 16
}
if (-not $envVars['AMADBAN_ADMIN_PASSWORD'] -or $envVars['AMADBAN_ADMIN_PASSWORD'].Length -lt 12) {
    $envVars['AMADBAN_ADMIN_PASSWORD'] = New-AmadbanPassword 16
}
$envVars['AMADBAN_KEYS'] = $keys
$envVars['ASPNETCORE_URLS'] = "http://0.0.0.0:$LanPort"
$envVars['ASPNETCORE_ENVIRONMENT'] = 'Production'

if (-not $pgVars['POSTGRES_SUPER_PASSWORD']) {
    $pgVars['POSTGRES_SUPER_PASSWORD'] = New-AmadbanPassword 24
}

$superPassword = $pgVars['POSTGRES_SUPER_PASSWORD']

if (-not (Test-PostgresReady $superPassword)) {
    $installer = Find-PostgresInstaller $postgresBundle
    $anyPg = Get-Service -Name 'postgresql*' -ErrorAction SilentlyContinue | Where-Object { $_.Status -eq 'Running' } | Select-Object -First 1
    if ($installer) {
        Install-PostgresFromBundle $installer $superPassword $dataRoot $PostgresServiceName
    }
    elseif ($anyPg) {
        Write-Step "Using existing PostgreSQL service: $($anyPg.Name)"
        if (-not (Test-PostgresReady $superPassword)) {
            Write-Warning 'Existing PostgreSQL found but superuser password does not match postgres.env.'
            Write-Warning "Set POSTGRES_SUPER_PASSWORD in $pgMeta to your postgres user password, then re-run."
            throw 'Cannot connect to PostgreSQL'
        }
    }
    else {
        throw @"
PostgreSQL is not running and no offline installer was found.
Copy postgresql-*-windows-x64.exe into:
  $postgresBundle
See bundle/README.md
"@
    }
    if (-not (Test-PostgresReady $superPassword)) { throw 'PostgreSQL installed but not accepting connections' }
}

Write-Step 'Creating amadban database user'
Ensure-AmadbanDatabase $envVars['AMADBAN_DB_PASSWORD'] $superPassword

Write-Step "Copying application to $publish"
if (Test-Path $publish) { Remove-Item $publish -Recurse -Force }
Copy-Item -Path (Join-Path $appSrc '*') -Destination $publish -Recurse -Force

Write-ServiceEnv $envFile $envVars
Set-Content -Path $pgMeta -Encoding UTF8 -Value @(
    '# PostgreSQL superuser password - protect this file',
    "POSTGRES_SUPER_PASSWORD=$superPassword",
    "POSTGRES_SERVICE=$PostgresServiceName"
)

$ruleName = 'Amadban HTTP (LAN)'
if (-not (Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue)) {
    New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Protocol TCP -LocalPort $LanPort -Action Allow | Out-Null
}

$exe = Join-Path $publish 'Amadban.exe'
$dll = Join-Path $publish 'Amadban.dll'
if (Test-Path $exe) { $binPath = "`"$exe`"" }
elseif (Test-Path $dll) {
    $dotnetCmd = Get-Command dotnet -ErrorAction SilentlyContinue
    $dotnet = if ($dotnetCmd) { $dotnetCmd.Source } else { $null }
    if (-not $dotnet) { throw 'Amadban.dll publish requires dotnet on server; rebuild bundle with self-contained app.' }
    $binPath = "`"$dotnet`" `"$dll`""
}
else { throw 'Amadban.exe or Amadban.dll missing in publish' }

$serviceName = 'Amadban'
$svc = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
if ($svc) {
    if ($svc.Status -eq 'Running') { Stop-Service $serviceName -Force }
    sc.exe delete $serviceName | Out-Null
    Start-Sleep -Seconds 2
}

sc.exe create $serviceName binPath= $binPath start= auto DisplayName= "Amadban hospital LAN" | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'sc.exe create failed' }

$regPath = "HKLM:\SYSTEM\CurrentControlSet\Services\$serviceName"
$envList = $envVars.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" }
Set-ItemProperty -Path $regPath -Name Environment -Value $envList -Type MultiString -Force

Write-Step 'Starting Amadban service'
Start-Service $serviceName
Start-Sleep -Seconds 6
$status = (Get-Service $serviceName).Status
if ($status -ne 'Running') { throw 'Amadban service did not start. See Application event log.' }

Write-Host ''
Write-Host '========================================' -ForegroundColor Green
Write-Host '  Amadban installed OK.' -ForegroundColor Green
Write-Host "  LAN: http://<server-ip>:$LanPort/Login" -ForegroundColor Green
Write-Host '  Login: admin' -ForegroundColor Green
Write-Host "  Admin password: $($envVars['AMADBAN_ADMIN_PASSWORD'])" -ForegroundColor Yellow
Write-Host "  Saved in: $envFile" -ForegroundColor Yellow
Write-Host '========================================' -ForegroundColor Green